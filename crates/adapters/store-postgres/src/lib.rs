//! Postgres [`RunRepository`] — persistence adapter for the `runs` table
//! (see `PLAN.md` §7). Backed by the bundled, in-cluster PostgreSQL StatefulSet
//! from the Helm chart (`dependencies.postgres`).

use std::time::{Duration, SystemTime, UNIX_EPOCH};

use cat_herder_domain::entities::{Run, RunId, RunKind, RunState, TenantId};
use cat_herder_domain::ports::{DomainResult, RunRepository};
use sqlx::postgres::{PgPool, PgRow};
use sqlx::Row;

/// A single `runs` row (schema created idempotently on `connect`).
#[derive(Clone)]
pub struct PostgresRunRepository {
    pool: PgPool,
}

impl PostgresRunRepository {
    /// Connect, create the pool, and ensure the schema exists.
    pub async fn connect(url: &str) -> DomainResult<Self> {
        let pool = PgPool::connect(url).await?;
        // Split into two statements: sqlx uses the extended (prepared) protocol
        // for parameterized queries, which rejects multiple commands per PREPARE.
        sqlx::query(
            "CREATE TABLE IF NOT EXISTS runs (\n\
                 id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,\n\
                 tenant_id       BIGINT      NOT NULL,\n\
                 kind            TEXT        NOT NULL,\n\
                 state           TEXT        NOT NULL,\n\
                 task_spec       TEXT        NOT NULL,\n\
                 max_concurrency INTEGER     NOT NULL,\n\
                 created_at      BIGINT      NOT NULL\n\
             )",
        )
        .execute(&pool)
        .await?;
        sqlx::query("CREATE INDEX IF NOT EXISTS runs_tenant_idx ON runs (tenant_id)")
            .execute(&pool)
            .await?;
        Ok(Self { pool })
    }
}

impl RunRepository for PostgresRunRepository {
    async fn save(&self, run: &Run) -> DomainResult<Run> {
        let tenant = run.tenant.0 as i64;
        let kind = encode_kind(run.kind);
        let state = encode_state(run.state);
        let created_ms = millis(run.created_at);

        let id: i64 = if run.id == RunId(0) {
            sqlx::query_scalar(
                "INSERT INTO runs (tenant_id, kind, state, task_spec, max_concurrency, created_at) \
                 VALUES ($1, $2, $3, $4, $5, $6) RETURNING id",
            )
            .bind(tenant)
            .bind(&kind)
            .bind(&state)
            .bind(&run.task_spec)
            .bind(run.max_concurrency as i32)
            .bind(created_ms)
            .fetch_one(&self.pool)
            .await?
        } else {
            sqlx::query_scalar(
                "INSERT INTO runs (id, tenant_id, kind, state, task_spec, max_concurrency, created_at) \
                 VALUES ($1, $2, $3, $4, $5, $6, $7) \
                 ON CONFLICT (id) DO UPDATE SET \
                   tenant_id = EXCLUDED.tenant_id, kind = EXCLUDED.kind, state = EXCLUDED.state, \
                   task_spec = EXCLUDED.task_spec, max_concurrency = EXCLUDED.max_concurrency, \
                   created_at = EXCLUDED.created_at \
                 RETURNING id",
            )
            .bind(run.id.0 as i64)
            .bind(tenant)
            .bind(&kind)
            .bind(&state)
            .bind(&run.task_spec)
            .bind(run.max_concurrency as i32)
            .bind(created_ms)
            .fetch_one(&self.pool)
            .await?
        };

        Ok(Run {
            id: RunId(id as u64),
            ..run.clone()
        })
    }

    async fn get(&self, id: RunId) -> DomainResult<Option<Run>> {
        let row = sqlx::query("SELECT * FROM runs WHERE id = $1")
            .bind(id.0 as i64)
            .fetch_optional(&self.pool)
            .await?;
        row.as_ref().map(run_from_row).transpose().map_err(Into::into)
    }

    async fn list_by_tenant(&self, tenant: TenantId) -> DomainResult<Vec<Run>> {
        let rows = sqlx::query("SELECT * FROM runs WHERE tenant_id = $1 ORDER BY id")
            .bind(tenant.0 as i64)
            .fetch_all(&self.pool)
            .await?;
        rows.iter().map(run_from_row).collect::<Result<Vec<_>, _>>().map_err(Into::into)
    }

    async fn list_all(&self) -> DomainResult<Vec<Run>> {
        let rows = sqlx::query("SELECT * FROM runs ORDER BY id")
            .fetch_all(&self.pool)
            .await?;
        rows.iter().map(run_from_row).collect::<Result<Vec<_>, _>>().map_err(Into::into)
    }
}

// --- row mapping -----------------------------------------------------------

fn run_from_row(row: &PgRow) -> Result<Run, sqlx::Error> {
    Ok(Run {
        id: RunId(row.try_get::<i64, _>("id")? as u64),
        tenant: TenantId(row.try_get::<i64, _>("tenant_id")? as u64),
        kind: decode_kind(&row.try_get::<String, _>("kind")?),
        state: decode_state(&row.try_get::<String, _>("state")?),
        task_spec: row.try_get("task_spec")?,
        max_concurrency: row.try_get::<i32, _>("max_concurrency")? as u32,
        created_at: from_millis(row.try_get::<i64, _>("created_at")?),
    })
}

// --- encode/decode (mirror the serde snake_case used by the JSON API) ------

fn encode_state(s: RunState) -> String {
    serde_json::to_value(s)
        .expect("state serializes")
        .as_str()
        .expect("state serializes to a string")
        .to_string()
}

fn decode_state(s: &str) -> RunState {
    serde_json::from_value(serde_json::Value::String(s.to_string())).unwrap_or(RunState::Failed)
}

fn encode_kind(k: RunKind) -> String {
    serde_json::to_value(k)
        .expect("kind serializes")
        .as_str()
        .expect("kind serializes to a string")
        .to_string()
}

fn decode_kind(s: &str) -> RunKind {
    serde_json::from_value(serde_json::Value::String(s.to_string())).unwrap_or(RunKind::Agent)
}

// --- time ------------------------------------------------------------------

fn millis(t: SystemTime) -> i64 {
    t.duration_since(UNIX_EPOCH)
        .map(|d| d.as_millis() as i64)
        .unwrap_or(0)
}

fn from_millis(ms: i64) -> SystemTime {
    if ms <= 0 {
        UNIX_EPOCH
    } else {
        UNIX_EPOCH + Duration::from_millis(ms as u64)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn state_roundtrips_all_variants() {
        let states = [
            RunState::Queued,
            RunState::Scheduled,
            RunState::PodPending,
            RunState::Running,
            RunState::AwaitingInput,
            RunState::BudgetPaused,
            RunState::Succeeded,
            RunState::AwaitingReview,
            RunState::Reviewed,
            RunState::Rejected,
            RunState::Failed,
            RunState::TimedOut,
            RunState::Cancelled,
            RunState::Stuck,
        ];
        for s in states {
            assert_eq!(decode_state(&encode_state(s)), s);
        }
    }

    #[test]
    fn kind_roundtrips_all_variants() {
        assert_eq!(decode_kind(&encode_kind(RunKind::Agent)), RunKind::Agent);
        assert_eq!(decode_kind(&encode_kind(RunKind::Workflow)), RunKind::Workflow);
    }

    #[test]
    fn state_encoding_matches_snake_case() {
        assert_eq!(encode_state(RunState::PodPending), "pod_pending");
        assert_eq!(encode_state(RunState::AwaitingInput), "awaiting_input");
        assert_eq!(encode_state(RunState::Succeeded), "succeeded");
    }

    #[test]
    fn time_roundtrips() {
        let t = SystemTime::now();
        assert_eq!(from_millis(millis(t)).duration_since(UNIX_EPOCH).unwrap().as_secs(),
                   t.duration_since(UNIX_EPOCH).unwrap().as_secs());
    }

    // Live round-trip against a real Postgres. Skipped unless a test DB URL is set
    // (e.g. `CAT_HERDER_TEST_DATABASE_URL=postgres://... cargo test -p cat-herder-store-postgres`).
    #[tokio::test]
    async fn postgres_roundtrip() {
        let Some(url) = std::env::var("CAT_HERDER_TEST_DATABASE_URL").ok() else {
            eprintln!("skipping postgres_roundtrip: CAT_HERDER_TEST_DATABASE_URL not set");
            return;
        };
        let repo = PostgresRunRepository::connect(&url).await.expect("connect");

        let run = Run {
            id: RunId(0),
            tenant: TenantId(42),
            kind: RunKind::Agent,
            state: RunState::Queued,
            task_spec: "persist me".into(),
            max_concurrency: 3,
            created_at: SystemTime::now(),
        };
        let saved = repo.save(&run).await.expect("save assigns id");
        assert_ne!(saved.id, RunId(0));

        let got = repo.get(saved.id).await.expect("get").expect("row exists");
        assert_eq!(got.id, saved.id);
        assert_eq!(got.tenant, TenantId(42));
        assert_eq!(got.task_spec, "persist me");
        assert_eq!(got.state, RunState::Queued);

        // Update in place (upsert path).
        let mut updated = saved.clone();
        updated.state = RunState::Succeeded;
        repo.save(&updated).await.expect("upsert");
        assert_eq!(repo.get(saved.id).await.unwrap().unwrap().state, RunState::Succeeded);

        // List by tenant.
        assert!(repo.list_by_tenant(TenantId(42)).await.unwrap().iter().any(|r| r.id == saved.id));
    }
}
